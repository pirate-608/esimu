def _write_agent_file(target: Path, args: argparse.Namespace) -> None:
    template = (_source_root() / "templates" / "agent" / "AGENTS.md").read_text(
        encoding="utf-8"
    )
    replacements = {
        "<project-name>": args.project_name,
        "<absolute-project-root>": ".",
        "<theme-id>": args.theme_id,
        "<backend-path>": "apps/starter/backend",
        "<frontend-path>": "apps/starter/frontend",
        "<theme-path>": f"themes/{args.theme_id}",
        "<python>": "python",
        "<validate-world-data-script>": (
            f"-m esimu_core.cli --root . --theme {args.theme_id}"
        ),
        "<backend-tests-path>": "apps/starter/backend/tests",
        "<backend-app-path>": "apps/starter/backend/app",
        "<compatibility-id-1>": "forum",
        "<compatibility-id-2>": "messenger",
    }
    for old, new in replacements.items():
        template = template.replace(old, new)
    (target / "AGENTS.md").write_text(template, encoding="utf-8")


def bootstrap_project(args: argparse.Namespace) -> Path:
    """Create a new project directory from the starter app and source theme."""
    target = args.target.expanduser().resolve()
    if target.exists() and any(target.iterdir()) and not args.force:
        raise ValueError(f"target already exists and is not empty: {target}")
    target.mkdir(parents=True, exist_ok=True)

    source_root = _source_root()
    starter_source = source_root / "apps" / "starter"
    theme_source = source_root / "themes" / args.source_theme
    if not starter_source.exists():
        raise ValueError(f"starter source not found: {starter_source}")
    if not theme_source.exists():
        raise ValueError(f"source theme not found: {theme_source}")

    _copytree_filtered(starter_source, target / "apps" / "starter")
    scripts_target = target / "scripts"
    scripts_target.mkdir(parents=True, exist_ok=True)
    for script_name in ("scaffold_game_stat.py", "scaffold_world_data.py"):
        shutil.copy2(
            source_root / "packages" / "esimu-core" / "scripts" / script_name,
            scripts_target / script_name,
        )
    theme_target = target / "themes" / args.theme_id
    _copytree_filtered(theme_source, theme_target)

    theme = _read_json(theme_target / "theme.json")
    theme["theme_id"] = args.theme_id
    theme["display_name"] = args.display_name
    theme.setdefault("storage", {})["prefix"] = args.storage_prefix
    terms = theme.setdefault("terms", {})
    terms["institution"] = args.institution
    terms["institution_short"] = args.institution_short
    terms["campus"] = args.institution
    terms["forum"] = args.forum_name
    terms["messenger"] = args.messenger_name
    _write_json(theme_target / "theme.json", theme)

    story = _read_json(theme_target / "story.json")
    _copy_story_assets(theme_target, story)
    _patch_starter_files(target, args.theme_id, args.core_dependency)
    _write_generated_frontend_data(target, args.theme_id)
    _write_project_docs(target, args)
    _write_agent_file(target, args)
    return target


def build_parser() -> argparse.ArgumentParser:
    """Build the CLI parser."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("target", type=Path, help="directory to create")
    parser.add_argument(
        "--project-name", default="", help="human-readable project name"
    )
    parser.add_argument("--theme-id", default="", help="theme id, e.g. star-campus")
    parser.add_argument("--display-name", default="", help="visible simulator title")
    parser.add_argument("--institution", default="", help="main institution/place name")
    parser.add_argument(
        "--institution-short", default="", help="short institution name"
    )
    parser.add_argument("--forum-name", default="", help="forum/feed community name")
    parser.add_argument(
        "--messenger-name", default="", help="messenger/private-chat name"
    )
    parser.add_argument(
        "--storage-prefix", default="", help="browser storage key prefix"
    )
    parser.add_argument("--source-theme", default="demo-campus", help="theme to copy")
    parser.add_argument(
        "--core-dependency",
        default=DEFAULT_CORE_DEPENDENCY,
        help="requirements.txt dependency line for esimu-core",
    )
    parser.add_argument(
        "--force", action="store_true", help="allow writing into a non-empty target"
    )
    return parser


def normalize_args(args: argparse.Namespace) -> argparse.Namespace:
    """Fill derived defaults after argparse has parsed user input."""
    args.project_name = args.project_name or args.target.name.replace("-", " ").title()
    args.theme_id = args.theme_id or _slug(args.project_name)
    args.display_name = args.display_name or args.project_name
    args.institution = args.institution or args.display_name
    args.institution_short = args.institution_short or args.institution
    args.forum_name = args.forum_name or f"{args.institution_short}论坛"
    args.messenger_name = args.messenger_name or "校内信"
    args.storage_prefix = args.storage_prefix or _storage_prefix(args.theme_id)
    return args


def main(argv: list[str] | None = None) -> int:
    """CLI entry point."""
    parser = build_parser()
    args = normalize_args(parser.parse_args(argv))
    try:
        target = bootstrap_project(args)
    except Exception as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    print(f"created esimu project at {target}")
    print(f"theme: {args.theme_id}")
    print(f"next: run esimu validate --root {target} --theme {args.theme_id}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
